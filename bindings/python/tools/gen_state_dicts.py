#!/usr/bin/env python3
"""Generate src/state_dicts.cpp: nanopb state structs -> Python dicts.

Parses the oneof fields (which_optional_X / which_option_X) out of the
generated headers and emits one `put(...)` line per scalar field. Nested
structs, LatLong and unbounded pb_callback_t strings are skipped; the few
fields needing text mapping (charge state, vehicle status, media) are
hand-written in the template below.

Run from bindings/python:  python3 tools/gen_state_dicts.py
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HEADER = ROOT / "generated" / "include" / "vehicle.pb.h"
OUT = Path(__file__).resolve().parents[1] / "cpp" / "state_dicts.cpp"

STRUCTS = [
    "CarServer_ChargeState",
    "CarServer_ClimateState",
    "CarServer_ClosuresState",
    "CarServer_DriveState",
    "CarServer_TirePressureState",
    "CarServer_MediaState",
]

EXCLUDED = {
    "home_location",
    "work_location",
    "active_route_destination",
    "now_playing_artist",
    "now_playing_title",
}

# struct -> (python function name, C++ parameter name)
FUNCS = {
    "CarServer_ChargeState": "charge_state_to_dict",
    "CarServer_ClimateState": "climate_state_to_dict",
    "CarServer_ClosuresState": "closures_state_to_dict",
    "CarServer_DriveState": "drive_state_to_dict",
    "CarServer_TirePressureState": "tire_pressure_state_to_dict",
}

SPECIAL_TAIL = {
    "CarServer_ChargeState": """
  if (s.has_charging_state) {
    d["charging_state"] = TeslaBLE::state_text::charging_state(s.charging_state.which_type);
    d["charging_state_raw"] = s.charging_state.which_type;
  }
  if (s.which_optional_charge_limit_reason) {
    d["charge_limit_reason"] =
        TeslaBLE::state_text::charge_limit_reason(s.optional_charge_limit_reason.charge_limit_reason);
  }
  if (s.has_charge_port_latch) {
    d["charge_port_latch"] = s.charge_port_latch.which_type;
  }
""",
    "CarServer_ClimateState": """
  if (s.has_climate_keeper_mode) {
    d["climate_keeper_mode"] = s.climate_keeper_mode.which_type;
  }
  if (s.has_defrost_mode) {
    d["defrost_mode"] = s.defrost_mode.which_type;
  }
""",
    "CarServer_DriveState": """
  if (s.has_shift_state) {
    d["shift_state"] = TeslaBLE::state_text::shift_state(s.shift_state.which_type);
    d["shift_state_raw"] = s.shift_state.which_type;
  }
""",
    "CarServer_ClosuresState": """
  if (s.has_sentry_mode_state) {
    d["sentry_mode_state"] = s.sentry_mode_state.which_type;
  }
""",
}


def struct_fields(name: str) -> list[tuple[str, str]]:
    """Return (which_member, union_member) pairs for one struct."""
    text = HEADER.read_text()
    match = re.search(rf"typedef struct _{name} \{{(.*?)\}} {name};", text, re.S)
    if not match:
        sys.exit(f"struct {name} not found in {HEADER}")
    body = match.group(1)
    fields = []
    for m in re.finditer(r"which_(optional|option)_([a-z0-9_]+);", body):
        prefix, field = m.group(1), m.group(2)
        if field in EXCLUDED:
            continue
        fields.append((f"which_{prefix}_{field}", f"{prefix}_{field}"))
    return fields


def emit_struct(name: str) -> str:
    lines = []
    for which, union in struct_fields(name):
        inner = union.split("_", 1)[1]
        lines.append(f'  put(d, "{inner}", s.{which}, s.{union}.{inner});')
    body = "\n".join(lines)
    tail = SPECIAL_TAIL.get(name, "")
    return (
        f"py::dict {FUNCS[name]}(const {name} &s) {{\n"
        f"  py::dict d;\n{body}\n{tail}  return d;\n"
        f"}}\n"
    )


HEADER_TEXT = '''// Generated by tools/gen_state_dicts.py - do not edit by hand.
// Converts nanopb state structs delivered by Vehicle callbacks into plain
// Python dicts. Only fields that are set (which_* != 0) are included.

#include "state_dicts.h"

#include "state_text.h"

#include <pybind11/pybind11.h>

#include <type_traits>

namespace py = pybind11;

namespace tesla_ble_python {

namespace {

// nanopb enums are plain C enums; they are exposed as their integer value.
// Non-scalar oneof members (nested structs, callbacks) are skipped because
// they have no Python representation; exposing them as raw objects would
// raise "Unregistered type" at runtime, as happened with real-vehicle
// fields such as scheduled_charging_mode.
template<typename T>
void put(py::dict &d, const char *key, pb_size_t which, const T &value) {
  if (which != 0) {
    if constexpr (std::is_enum_v<T>) {
      d[key] = static_cast<std::underlying_type_t<T>>(value);
    } else if constexpr (std::is_arithmetic_v<T>) {
      d[key] = value;
    }
  }
}

}  // namespace

'''

VEHICLE_STATUS = '''
py::dict vehicle_status_to_dict(const VCSEC_VehicleStatus &s) {
  py::dict d;
  if (auto unlocked = TeslaBLE::state_text::lock_status(static_cast<int>(s.vehicleLockState))) {
    d["locked"] = !*unlocked;
  }
  d["lock_state_raw"] = static_cast<int>(s.vehicleLockState);
  if (auto asleep = TeslaBLE::state_text::sleep_status(static_cast<int>(s.vehicleSleepStatus))) {
    d["asleep"] = *asleep;
  }
  d["sleep_state_raw"] = static_cast<int>(s.vehicleSleepStatus);
  if (auto present = TeslaBLE::state_text::user_presence(static_cast<int>(s.userPresence))) {
    d["user_present"] = *present;
  }
  d["user_presence_raw"] = static_cast<int>(s.userPresence);
  if (s.has_closureStatuses) {
    py::dict closures;
    py::dict closures_raw;
    closures["front_driver_door"] = TeslaBLE::state_text::closure_state_text(s.closureStatuses.frontDriverDoor);
    closures["front_passenger_door"] = TeslaBLE::state_text::closure_state_text(s.closureStatuses.frontPassengerDoor);
    closures["rear_driver_door"] = TeslaBLE::state_text::closure_state_text(s.closureStatuses.rearDriverDoor);
    closures["rear_passenger_door"] = TeslaBLE::state_text::closure_state_text(s.closureStatuses.rearPassengerDoor);
    closures["rear_trunk"] = TeslaBLE::state_text::closure_state_text(s.closureStatuses.rearTrunk);
    closures["front_trunk"] = TeslaBLE::state_text::closure_state_text(s.closureStatuses.frontTrunk);
    closures["charge_port"] = TeslaBLE::state_text::closure_state_text(s.closureStatuses.chargePort);
    closures["tonneau"] = TeslaBLE::state_text::closure_state_text(s.closureStatuses.tonneau);
    closures_raw["front_driver_door"] = static_cast<int>(s.closureStatuses.frontDriverDoor);
    closures_raw["front_passenger_door"] = static_cast<int>(s.closureStatuses.frontPassengerDoor);
    closures_raw["rear_driver_door"] = static_cast<int>(s.closureStatuses.rearDriverDoor);
    closures_raw["rear_passenger_door"] = static_cast<int>(s.closureStatuses.rearPassengerDoor);
    closures_raw["rear_trunk"] = static_cast<int>(s.closureStatuses.rearTrunk);
    closures_raw["front_trunk"] = static_cast<int>(s.closureStatuses.frontTrunk);
    closures_raw["charge_port"] = static_cast<int>(s.closureStatuses.chargePort);
    closures_raw["tonneau"] = static_cast<int>(s.closureStatuses.tonneau);
    d["closures"] = closures;
    d["closures_raw"] = closures_raw;
  }
  if (s.has_detailedClosureStatus) {
    d["tonneau_percent_open"] = s.detailedClosureStatus.tonneauPercentOpen;
  }
  return d;
}
'''

MEDIA = '''
py::dict media_state_to_dict(const CarServer_MediaState &s, const TeslaBLE::MediaNowPlaying &now_playing) {
  py::dict d;
  put(d, "audio_volume", s.which_optional_audio_volume, s.optional_audio_volume.audio_volume);
  put(d, "audio_volume_increment", s.which_optional_audio_volume_increment,
      s.optional_audio_volume_increment.audio_volume_increment);
  put(d, "audio_volume_max", s.which_optional_audio_volume_max, s.optional_audio_volume_max.audio_volume_max);
  put(d, "now_playing_source", s.which_optional_now_playing_source, s.optional_now_playing_source.now_playing_source);
  put(d, "media_playback_status", s.which_optional_media_playback_status,
      s.optional_media_playback_status.media_playback_status);
  put(d, "remote_control_enabled", s.which_optional_remote_control_enabled,
      s.optional_remote_control_enabled.remote_control_enabled);
  if (now_playing.has_artist) {
    d["now_playing_artist"] = now_playing.artist;
  }
  if (now_playing.has_title) {
    d["now_playing_title"] = now_playing.title;
  }
  return d;
}
'''

SOFTWARE_UPDATE = '''
py::dict software_update_state_to_dict(const CarServer_SoftwareUpdateState &s, const std::string &version) {
  py::dict d;
  if (s.has_status) {
    d["status"] = static_cast<int>(s.status.which_type);
  }
  put(d, "scheduled_time_ms", s.which_optional_scheduled_time_ms, s.optional_scheduled_time_ms.scheduled_time_ms);
  put(d, "warning_time_remaining_ms", s.which_optional_warning_time_remaining_ms,
      s.optional_warning_time_remaining_ms.warning_time_remaining_ms);
  put(d, "expected_duration_sec", s.which_optional_expected_duration_sec,
      s.optional_expected_duration_sec.expected_duration_sec);
  put(d, "download_perc", s.which_optional_download_perc, s.optional_download_perc.download_perc);
  put(d, "install_perc", s.which_optional_install_perc, s.optional_install_perc.install_perc);
  if (!version.empty()) {
    d["version"] = version;
  }
  return d;
}
'''


def main() -> None:
    parts = [HEADER_TEXT]
    for name in STRUCTS:
        if name == "CarServer_MediaState":
            continue
        parts.append(emit_struct(name))
    parts.append(VEHICLE_STATUS)
    parts.append(MEDIA)
    parts.append(SOFTWARE_UPDATE)
    parts.append("\n}  // namespace tesla_ble_python\n")
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
